"""Chapter 3: how big search spaces are.

1. The whole 8-puzzle state space by breadth-first search from the goal: how
   many states lie at each distance, and a check that exactly half of the
   9!/1 arrangements are reachable (the parity argument of Section 3.1).
2. What exponential growth costs: time and memory of breadth-first search for
   branching factor 10, under stated assumptions.
3. The overhead of iterative deepening: nodes generated by IDS and by BFS.
Standard library only.
"""
from collections import deque
from itertools import permutations
from math import factorial

from ch03_search import EightPuzzle, solvable


def bfs_layers(goal):
    p = EightPuzzle(goal)
    dist = {goal: 0}
    q = deque([goal])
    while q:
        s = q.popleft()
        for a in p.actions(s):
            t = p.result(s, a)
            if t not in dist:
                dist[t] = dist[s] + 1
                q.append(t)
    return dist


def main():
    goal = EightPuzzle.GOAL
    dist = bfs_layers(goal)
    layers = [0] * (max(dist.values()) + 1)
    for d in dist.values():
        layers[d] += 1
    print(f"8-puzzle: {len(dist)} states reachable from the goal; 9! = {factorial(9)}")
    print("  states at each distance from the goal:")
    for start in range(0, len(layers), 8):
        row = "  ".join(f"{d:2d}:{layers[d]:6d}" for d in
                        range(start, min(start + 8, len(layers))))
        print("   ", row)
    far = [s for s, d in dist.items() if d == len(layers) - 1]
    print(f"  the farthest states ({len(layers) - 1} moves): {far}")
    agree = all((s in dist) == solvable(s) for s in permutations(range(9)))
    print(f"  reachable exactly when the inversion parity matches the goal: {agree}")

    print("\nbreadth-first search with b = 10, 1 million nodes per second,"
          " 1 kilobyte per node:")
    for d in (2, 4, 6, 8, 10, 12, 14, 16):
        nodes = sum(10 ** i for i in range(d + 1))
        secs = nodes / 1e6
        t = (f"{secs:.3g} seconds" if secs < 3600 else
             f"{secs / 3600:.3g} hours" if secs < 86400 * 365 else
             f"{secs / (86400 * 365.25):.3g} years")
        size, unit = nodes * 1e3, "bytes"
        for u in ("kB", "MB", "GB", "TB", "PB", "EB"):
            if size >= 1000:
                size, unit = size / 1000, u
        print(f"  depth {d:2d}: {nodes:>22,} nodes, {t:>16}, {size:6.3g} {unit}")

    print("\nnodes generated: IDS against BFS (complete tree, branching b, depth d)")
    for b, d in [(2, 10), (3, 8), (10, 5), (10, 10)]:
        ids = sum((d + 1 - i) * b ** i for i in range(1, d + 1))
        bfs = sum(b ** i for i in range(1, d + 1))
        print(f"  b = {b:2d}, d = {d:2d}: IDS {ids:>14,}  BFS {bfs:>14,}"
              f"  ratio {ids / bfs:.3f}  (b/(b-1) = {b / (b - 1):.3f})")


if __name__ == "__main__":
    main()
